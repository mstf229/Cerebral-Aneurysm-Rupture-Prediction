axes = axes.ravel()

panel_labels = ["a)", "b)", "c)", "d)"]

# ------------------------------------------------
# Function to crop image
# ------------------------------------------------
def manual_crop(img, crop_dict):
    w, h = img.size

    left = crop_dict["left"]
    right = crop_dict["right"]
    top = crop_dict["top"]
    bottom = crop_dict["bottom"]
    mode = crop_dict["mode"]

    if mode == "frac":
        left   = int(left   * w)
        right  = int(right  * w)
        top    = int(top    * h)
        bottom = int(bottom * h)

    x0 = left
    x1 = w - right
    y0 = top
    y1 = h - bottom

    return img.crop((x0, y0, x1, y1))

# ------------------------------------------------
# Build figure
# ------------------------------------------------
